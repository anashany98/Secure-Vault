import { randomBytes } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';

const repoRoot = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const targetPath = path.join(repoRoot, 'deploy', 'securevault.secrets.env');

function generateSecret() {
  return randomBytes(48).toString('base64url');
}

function parseEnvFile(content) {
  return content.split(/\r?\n/).reduce((accumulator, line) => {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) {
      return accumulator;
    }

    const separatorIndex = trimmed.indexOf('=');
    if (separatorIndex === -1) {
      return accumulator;
    }

    const key = trimmed.slice(0, separatorIndex).trim();
    const value = trimmed.slice(separatorIndex + 1).trim();
    accumulator[key] = value;
    return accumulator;
  }, {});
}

function buildContent(values) {
  return [
    '# Generated by scripts/generate-deployment-secrets.mjs',
    '# Preserve this file across deployments. Rotating these values without re-encrypting data will make stored secrets unreadable.',
    `JWT_SECRET=${values.JWT_SECRET}`,
    `CLIENT_VAULT_KEY=${values.CLIENT_VAULT_KEY}`,
    `CLIENT_NOTES_KEY=${values.CLIENT_NOTES_KEY}`,
    `BACKUP_ENCRYPTION_KEY=${values.BACKUP_ENCRYPTION_KEY}`,
    `POSTGRES_PASSWORD=${values.POSTGRES_PASSWORD}`,
    '',
  ].join('\n');
}

fs.mkdirSync(path.dirname(targetPath), { recursive: true });

const existing = fs.existsSync(targetPath)
  ? parseEnvFile(fs.readFileSync(targetPath, 'utf8'))
  : {};

const merged = {
  JWT_SECRET: existing.JWT_SECRET || generateSecret(),
  CLIENT_VAULT_KEY: existing.CLIENT_VAULT_KEY || generateSecret(),
  CLIENT_NOTES_KEY: existing.CLIENT_NOTES_KEY || generateSecret(),
  BACKUP_ENCRYPTION_KEY: existing.BACKUP_ENCRYPTION_KEY || generateSecret(),
  POSTGRES_PASSWORD: existing.POSTGRES_PASSWORD || generateSecret(),
};

fs.writeFileSync(targetPath, buildContent(merged));

console.log(`Secrets file ready: ${targetPath}`);
